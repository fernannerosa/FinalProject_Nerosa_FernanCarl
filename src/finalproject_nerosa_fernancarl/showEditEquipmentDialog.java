    // Process: Look up string values across dropdown item arrays to lock active configuration
    private void setSelectedStatus(String statusName) {
        if (statusName == null) return;
        for (int i = 0; i < statusComboBox.getItemCount(); i++) {
            if (statusComboBox.getItemAt(i).toString().equalsIgnoreCase(statusName.trim())) {
                statusComboBox.setSelectedIndex(i);
                break;
            }
        }
    }
