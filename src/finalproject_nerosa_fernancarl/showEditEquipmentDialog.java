    private void loadCategories() {
    categoryComboBox.removeAllItems();

    for (Category c : categoriesDAO.getAllCategories()) {
        categoryComboBox.addItem(c);
    }
}
    
    private void loadLocations() {
    locationComboBox.removeAllItems();
    // FIX: Ensure the variable type matches 'Location'
    for (Location loc : locationsDAO.getAllLocations()) { 
        locationComboBox.addItem(loc);
    }
}
    
    private void setSelectedCategoryByName(String name) {
        for (int i = 0; i < categoryComboBox.getItemCount(); i++) {
            if (categoryComboBox.getItemAt(i).getCategory_name().equalsIgnoreCase(name)) {
                categoryComboBox.setSelectedIndex(i);
                break;
            }
        }
    }

    private void setSelectedLocationByCode(String code) {
        for (int i = 0; i < locationComboBox.getItemCount(); i++) {
            if (locationComboBox.getItemAt(i).getLocation_code().equalsIgnoreCase(code)) {
                locationComboBox.setSelectedIndex(i);
                break;
            }
        }
    }

