    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
    String updatedName = nameField.getText().trim();
    String updatedBrand = brandField.getText().trim();
    String updatedModel = modelField.getText().trim();
    String updatedStatus = (String) statusComboBox.getSelectedItem(); // <-- Process: Extract user chosen status string
    
    Category selectedCategory = (Category) categoryComboBox.getSelectedItem();
    Location selectedLocation = (Location) locationComboBox.getSelectedItem();

    if (updatedName.isEmpty() || updatedBrand.isEmpty() || updatedModel.isEmpty() || 
        updatedStatus == null || selectedCategory == null || selectedLocation == null) {
        
        javax.swing.JOptionPane.showMessageDialog(this, 
            "All fields are required. Please populate all entries.", 
            "Validation Error", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Process: Execute database modifications via the DAO pipeline
    boolean specUpdated = equipmentDAO.updateEquipmentSpecs(itemId, updatedName, updatedBrand, updatedModel, selectedCategory.getCategory_id());
    
    // FIX: Update your DAO method call to accept the updatedStatus string variable parameter
    boolean itemUpdated = equipmentDAO.updateEquipmentItemDetails(itemId, selectedLocation.getLocation_id(), updatedStatus);

    if (specUpdated && itemUpdated) {
        javax.swing.JOptionPane.showMessageDialog(this, "Equipment updated successfully!");
        
        if (parentFrame != null) {
            parentFrame.refreshTableFromDatabase();
            parentFrame.updateFooterCount();
        }
        this.dispose();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Failed to save database modifications.", 
            "Database Error", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_saveBtnActionPerformed

